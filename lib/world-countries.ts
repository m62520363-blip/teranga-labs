/** 206 entrées, triées par nom français (affichage insensible à l'ordre). */
export const AFRICA_COUNTRIES: WorldCountry[] = AFRICA;

export const WORLD_COUNTRIES: WorldCountry[] = [...AFRICA, ...ASIA, ...EUROPE, ...AMERICAS, ...OCEANIA].sort(
  (a, b) => a.nameFr.localeCompare(b.nameFr, "fr")
);

const BY_ISO2: Record<string, WorldCountry> = Object.freeze(
  Object.fromEntries(WORLD_COUNTRIES.map((c) => [c.iso2, c]))
);

const BY_NAME_FR: Record<string, WorldCountry> = Object.freeze(
  Object.fromEntries(
    WORLD_COUNTRIES.map((c) => [c.nameFr.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase(), c])
  )
);

export function getWorldCountry(iso2: string | null | undefined): WorldCountry | undefined {
  if (!iso2) return undefined;
  return BY_ISO2[iso2.trim().toUpperCase()];
}

/**
 * Résout UN libellé de pays (tel que stocké dans `users.country`,
 * « Sénégal », « France », « United States »…) vers le référentiel monde.
 * Compare en normalisé (accents/casse) sur le nom FR, puis sur l'ISO2.
 */
export function findWorldCountryByName(name: string | null | undefined): WorldCountry | undefined {
  const raw = (name ?? "").trim();
  if (!raw) return undefined;
  const key = raw.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLowerCase();
  return BY_NAME_FR[key] ?? BY_ISO2[raw.toUpperCase()];
}

/** Map valeur→libellé pour la prop `items` des `Select` (base-ui). */
export const WORLD_COUNTRY_ITEMS: Record<string, string> = Object.freeze(
  Object.fromEntries(WORLD_COUNTRIES.map((c) => [c.iso2, c.nameFr]))
);

