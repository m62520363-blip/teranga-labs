/**
 * Liste du sélecteur d'indicatif : DÉDUPLIQUÉE par dial (premier gagne,
 * tri par nom FR). « +1 » → Canada/États-Unis : une seule entrée ; les
 * Caraïbes gardent leur dial complet (+1242, +1876…) donc leur entrée.
 * 204 entrées attendues (206 moins US/CA et RU/KZ fusionnés).
 */
export const WORLD_PHONE_COUNTRIES: WorldCountry[] = (() => {
  const seen = new Set<string>();
  const out: WorldCountry[] = [];
  for (const c of WORLD_COUNTRIES) {
    if (seen.has(c.dial)) continue;
    seen.add(c.dial);
    out.push(c);
  }
  return out;
})();

/** Dials triés par longueur décroissante (parse « plus long d'abord »). */
const DIALS_BY_LENGTH: string[] = [...new Set(WORLD_COUNTRIES.map((c) => c.dial))].sort(
  (a, b) => b.length - a.length
);

/** Fallback du sélecteur (siège légal). */
export const WORLD_DEFAULT_DIAL = "+221";

/**
 * Découpe un numéro international en { dial, national }.
 * - Sans « + » ni « 00 » : saisi nationale, rattachée à l'indicatif par
 *   défaut (aucune devinette, comme le sélecteur l'affiche).
 * - Avec « + »/« 00 » : test des dials du monde du plus long au plus
 *   court → « +12423333 » = Bahamas (+1242), jamais États-Unis (+1).
 */
export function parseWorldDial(value: string): { dial: string; national: string } {
  const raw = (value ?? "").trim();
  if (!raw) return { dial: WORLD_DEFAULT_DIAL, national: "" };
  const international = raw.startsWith("+") || raw.startsWith("00");
  const all = raw.replace(/\D/g, "");
  if (!international) return { dial: WORLD_DEFAULT_DIAL, national: all };
  const digits = raw.startsWith("00") ? all.slice(2) : all;
  if (!digits) return { dial: WORLD_DEFAULT_DIAL, national: "" };
  for (const dial of DIALS_BY_LENGTH) {
    const code = dial.slice(1);
    if (digits.startsWith(code) && digits.length > code.length) {
      return { dial, national: digits.slice(code.length) };
    }
  }
  return { dial: WORLD_DEFAULT_DIAL, national: digits };
}

