/** Régions du pays : périmètre d'abord, sinon référentiel monde. */
export function getWorldRegions(iso2: string | null | undefined): readonly string[] {
  if (!iso2) return [];
  const code = iso2.trim().toUpperCase();
  const scope = COUNTRIES.find((c) => c.iso2 === code);
  if (scope) return scope.regions.map((r) => r.name);
  return WORLD_REGIONS[code] ?? [];
}

