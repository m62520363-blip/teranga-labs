/**
 * Référentiel MONDE pour l'inscription (~205 pays et territoires).
 *
 * - `lib/countries.ts` reste LA source du périmètre géographique (9 pays,
 *   pages /ville et /pays, ciblage des briefs) : ne rien y ajouter ici.
 * - Ce référentiel sert à l'inscription (tous les pays, sans exception),
 *   à l'indicatif téléphonique et à la devise locale d'affichage.
 * - `dial` est l'indicatif E.164 complet avec « + ». Il peut être partagé
 *   par deux pays (US/CA : « +1 », RU/KZ : « +7 ») : le sélecteur
 *   téléphonique déduplique (voir `WORLD_PHONE_COUNTRIES`).
 * - `currency` est un code ISO 4217 connu de `lib/currency.ts`.
 */
export interface WorldCountry {
  iso2: string;
  nameFr: string;
  dial: string;
  currency: string;
}

